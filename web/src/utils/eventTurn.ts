/**
 * 事件正文里是否已经自带回合号。
 *
 * 背景：后端 `events[]` 的 `turn` 是**上报回合**，而 `text` 里写的是**发生回合**，
 * 两者常常差 1（实测：`{turn: 12, text: '第 11 回合: 4 场战斗'}`）。
 * 前端若在 text 前面再加一个「第{turn}回合」前缀，同一条记录就会显示两个
 * 互相矛盾的回合号 —— 实测输出「第12回合 第 11 回合: 4 场战斗」，
 * 观众无法判断战斗到底发生在哪一回合。
 *
 * 约定：**text 已自带回合号时，前端不再补前缀**（正文优先，它才是发生回合）。
 * 需要标注上报回合时另行设计文案，不要在同一行里并列两个数字。
 *
 * 匹配同时覆盖全角/半角空格写法：「第 11 回合」「第11回合」「第 11回合」。
 */
export function hasTurnInText(text: string | undefined | null): boolean {
  if (!text) return false
  return /第\s*\d+\s*回合/.test(text)
}
